using PowerPlanTray;
using System.Text.Json;

System.Globalization.CultureInfo.CurrentUICulture = System.Globalization.CultureInfo.GetCultureInfo("de-DE");
var count = 0;
void Check(bool condition, string description)
{
    if (!condition) throw new Exception(description);
    count++; Console.WriteLine($"PASS {description}");
}
var monday = new DateTime(2026, 10, 26, 8, 0, 0);
Check(!new AppSettings().CodexStandbyEnabled, "Fresh installations default Codex extension to off");
Check(!JsonSerializer.Deserialize<AppSettings>("{}")!.CodexStandbyEnabled, "Older settings without Codex preference default to off");
Check(JsonSerializer.Deserialize<AppSettings>("{\"CodexStandbyEnabled\":true}")!.CodexStandbyEnabled, "Explicit Codex opt-in survives restart");
var utc = new DateTimeOffset(2026, 10, 26, 7, 0, 0, TimeSpan.Zero);
var schedule = new EnergyRule { Kind = EnergyRuleKind.Schedule, PlanGuid = "time", Days = 2, StartMinute = 480, EndMinute = 1020 };
Check(!schedule.IsScheduled(monday.AddMinutes(-1)), "Schedule excludes time before start");
Check(schedule.IsScheduled(monday), "Schedule includes exact start");
Check(!schedule.IsScheduled(monday.AddHours(9)), "Schedule excludes exact end");
Check(!schedule.IsScheduled(monday.AddDays(1)), "Schedule respects selected weekday");
schedule.StartMinute = 22 * 60; schedule.EndMinute = 6 * 60;
Check(schedule.IsScheduled(monday.Date.AddHours(23)), "Overnight includes start evening");
Check(schedule.IsScheduled(monday.Date.AddDays(1).AddHours(5)), "Overnight uses previous weekday after midnight");
Check(!schedule.IsScheduled(monday.Date.AddHours(5)), "Overnight excludes previous unselected day");
Check(!schedule.IsScheduled(monday.Date.AddDays(1).AddHours(6)), "Overnight excludes exact end");
schedule.EndMinute = schedule.StartMinute;
Check(!schedule.IsScheduled(monday.Date.AddHours(23)), "Equal times do not silently become all day");
schedule.StartMinute = 480; schedule.EndMinute = 1020;

var app = new EnergyRule { Name = "VM", ProcessName = "vm.exe", PlanGuid = "app", DelaySeconds = 10, GraceSeconds = 20 };
var engine = new EnergyRuleEngine();
var available = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "app", "time" };
var running = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "VM" };
var empty = new HashSet<string>();
EnergyRule? Eval(int seconds, ISet<string> processes) => engine.Evaluate(new[] { app, schedule }, processes, available, utc.AddSeconds(seconds), monday);
Check(Eval(0, running) == schedule, "App delay allows lower priority schedule");
Check(Eval(9, running) == schedule, "Delay remains active before threshold");
Check(Eval(10, running) == app, "App wins at delay threshold, ignores executable case and extension");
Check(Eval(15, empty) == app, "App grace begins when process is absent");
Check(Eval(34, empty) == app, "App remains active during grace");
Check(Eval(35, empty) == schedule, "Grace expires at exact threshold");
Check(Eval(40, running) == schedule, "New app run must satisfy delay again");
Check(Eval(45, empty) == schedule, "Short app run does not activate grace");
Check(Eval(50, running) == schedule && Eval(60, running) == app, "Interrupted delay starts over");
app.Enabled = false;
Check(Eval(65, running) == schedule, "Disabled higher rule cannot win");
app.Enabled = true; app.DelaySeconds = 0;
Check(Eval(70, running) == app, "Re-enabled app reevaluates");
available.Remove("app");
Check(Eval(75, running) == schedule, "Unavailable plan does not block lower rule");
available.Add("app"); engine.Reset();
Check(EnergyRule.NormalizeProcess(@"C:\Program Files\VM\vm.exe") == "vm", "EXE picker normalizes paths");
var roundTrip = JsonSerializer.Deserialize<EnergyRule>(JsonSerializer.Serialize(app))!;
Check(roundTrip.Id == app.Id && roundTrip.GraceSeconds == 20, "Settings preserve rule identity and timings");

var calls = new List<string>();
bool success = true;
var automation = new EnergyPlanAutomation(plan => { calls.Add(plan); return success; });
automation.Update(app, "base");
Check(calls.SequenceEqual(new[] { "app" }), "First rule activates chosen plan");
automation.Update(app, "app");
Check(calls.Count == 1, "Steady active rule avoids redundant switches");
automation.Update(schedule, "app");
Check(calls.Last() == "time", "Priority transition changes plan");
automation.Update(null, "time");
Check(calls.Last() == "base", "End of overlapping rules restores original baseline");
calls.Clear(); automation.Update(app, "base"); automation.Update(app, "manual");
Check(automation.Paused && calls.Count == 1, "External manual plan pauses automation");
automation.Update(null, "manual");
Check(!automation.Paused && calls.Count == 1, "End of rules preserves manual plan and clears pause");
automation.Update(app, "manual"); automation.Pause(); automation.Update(app, "manual");
Check(automation.Paused, "Tray manual choice also pauses matching rules");
automation.Resume(); automation.Update(app, "manual"); automation.Restore("app");
Check(calls.Last() == "manual", "Resume uses manual plan as new baseline; exit restores it");
calls.Clear(); success = false; automation.Update(app, "base");
Check(automation.Status.Contains("fehlgeschlagen"), "Failed activation is reported");
automation.Update(null, "base");
Check(calls.Count == 1, "Failed activation never claims a restoration baseline");
success = true; calls.Clear(); automation.Update(app, null);
Check(calls.Count == 0, "Unreadable current plan never triggers an untracked switch");
automation.Update(app, "app"); automation.Update(null, "app");
Check(calls.Count == 0, "Already selected target needs no restore");
var vmRule = new EnergyRule { Kind = EnergyRuleKind.HyperV, VmId = "vm-one", VmName = "MK-VM01", PlanGuid = "app", DelaySeconds = 10, GraceSeconds = 20 };
var vmEngine = new EnergyRuleEngine();
EnergyRule? VmAt(int seconds, params string[] ids) => vmEngine.Evaluate(new[] { vmRule }, running, available, utc.AddSeconds(seconds), monday, new HashSet<string>(ids, StringComparer.OrdinalIgnoreCase));
Check(VmAt(0, "vm-two") is null, "Another Hyper-V VM cannot activate selected VM rule");
Check(VmAt(1, "VM-ONE") is null, "Selected VM begins start delay with case-insensitive ID");
Check(VmAt(11, "vm-one") == vmRule, "Selected VM activates at delay threshold");
vmRule.VmName = "Renamed VM";
Check(VmAt(12, "vm-one", "vm-two") == vmRule, "VM rename and other running VMs preserve ID match");
Check(VmAt(13, "vm-two") == vmRule, "Stopping selected VM begins grace");
Check(VmAt(33, "vm-two") is null, "Other running VM cannot extend selected VM grace");
var savedVm = JsonSerializer.Deserialize<EnergyRule>(JsonSerializer.Serialize(vmRule))!;
Check(savedVm.Kind == EnergyRuleKind.HyperV && savedVm.VmId == "vm-one" && savedVm.VmName == "Renamed VM", "Hyper-V identity survives settings persistence");
Check((int)EnergyRuleKind.App == 0 && (int)EnergyRuleKind.Schedule == 1, "Existing rule kind values remain compatible");
var priorCulture = System.Globalization.CultureInfo.CurrentUICulture;
